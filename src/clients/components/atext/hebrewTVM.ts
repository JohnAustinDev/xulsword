const Codes = new Map(TVM.map(([code, stem, mood]) => [code, { stem, mood }]));

// Return an entry for a Strong's Hebrew TVM code (like TH8804 or 8804), or
// null if code is not one.
export default function hebrewTVM(code: string): string | null {
  const n = Number(code.replace(/^T?H?0*/, ''));
  if (!n) return null;
  const title = `<span class="markup-title"><b>TH${n}</b></span>`;
  const special = Special.get(n);
  if (special) return `${title}<div class="markup-def">${special}</div>`;
  const tvm = Codes.get(n);
  if (!tvm) return null;
  return `${title}<div class="markup-def"><i>Stem</i>: ${tvm.stem}<br><i>Mood</i>: ${tvm.mood}</div>`;
}
